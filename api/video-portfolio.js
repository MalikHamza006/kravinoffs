export default function handler(req, res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'GET, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type');

  if (req.method === 'OPTIONS') {
    return res.status(200).end();
  }

  const { category, search, id } = req.query || {};

  if (id) {
    const item = VIDEO_PORTFOLIO.find(v => v.id === id);
    if (!item) {
      return res.status(404).json({ success: false, error: 'Video portfolio item not found.' });
    }
    return res.status(200).json({ success: true, item });
  }

  let results = [...VIDEO_PORTFOLIO];

  if (category && category !== 'All') {
    results = results.filter(v => v.category.toLowerCase().includes(category.toLowerCase()));
  }

  if (search) {
    const q = search.toLowerCase();
    results = results.filter(v => 
      v.title.toLowerCase().includes(q) ||
      v.brand.toLowerCase().includes(q) ||
      v.shortDesc.toLowerCase().includes(q) ||
      v.category.toLowerCase().includes(q)
    );
  }

  return res.status(200).json({
    success: true,
    count: results.length,
    total: VIDEO_PORTFOLIO.length,
    summary: MARKETING_CAMPAIGN_SUMMARY,
    videos: results
  });
}
